// Select a table by decimation factor x 10. Returns nullptr for a factor with no
// table, so analysis_config.h can stop the build with a message naming what is missing
// rather than filtering with the wrong coefficients.
constexpr const float *firTapsForDecimX10(uint16_t k) {
  return k ==  12 ? kFirTapsD12
       : k ==  24 ? kFirTapsD24
       : k ==  40 ? kFirTapsD40
       : k ==  48 ? kFirTapsD48
       : k ==  50 ? kFirTapsD50
       : k ==  60 ? kFirTapsD60
       : k ==  80 ? kFirTapsD80
       : k ==  96 ? kFirTapsD96
       : k == 100 ? kFirTapsD100
       : k == 120 ? kFirTapsD120
       : k == 192 ? kFirTapsD192
       :            nullptr;
}

