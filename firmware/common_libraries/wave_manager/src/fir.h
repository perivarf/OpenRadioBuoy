#ifndef FIR_H
#define FIR_H

#include <stdint.h>

/*
  Decimating FIR low-pass, the antialias filter the wave chain decimates through.
*/

// Filter kind per stage. The sinc kinds name the window; Mean is the moving mean over
// one output period. Must follow KINDS in tools/gen_fir_table.py.
enum class FirKind : uint8_t { Hamming, Hann, Blackman, Mean };

constexpr const char *firKindName(FirKind k) {
  return k == FirKind::Hamming  ? "hamming"
       : k == FirKind::Hann     ? "hann"
       : k == FirKind::Blackman ? "blackman"
       :                          "mean";
}

// Tap count of the mean: D for an odd D, D+1 for an even D (half weight at the ends) so
// the length stays odd. 0 for a fractional D, which has no table.
constexpr uint16_t firMeanNtap(uint16_t decimX10) {
  return decimX10 % 10 ? 0
       : (decimX10 / 10) % 2 ? (uint16_t)(decimX10 / 10)
       : (uint16_t)(decimX10 / 10 + 1);
}

template <uint16_t N>
class FirDecimator {
 public:
  static_assert(N % 2 == 1,
                "odd tap count - a linear-phase group delay of (N-1)/2 must be a whole "
                "number of samples, otherwise it cannot be compensated by indexing");

  static constexpr uint16_t kNtap = N;
  static constexpr uint16_t kHalf = (N - 1) / 2;  // group delay, in samples

  // coeffs must outlive the filter and hold N symmetric taps (see fir_coeffs.h,
  // generated by tools/gen_fir_table.py).
  explicit FirDecimator(const float *coeffs) : c_(coeffs) {}

  // Zero the delay line. The first N outputs after this are contaminated by the zero
  // fill - the capture warm-up covers that (see the warm-up assert in analysis_config.h).
  void reset(void) {
    for (uint16_t k = 0; k < N; k++) z_[k] = 0.0f;
    idx_ = 0;
  }

  // Store one input sample into the FIR - line.
  void push(float x) {
    z_[idx_] = x;

    // z_ is a Circular buffer, so idx_ wraps around.
    idx_ = (uint16_t)(idx_ + 1 == N ? 0 : idx_ + 1);
  }

  // Get one output sample. Does not advance the delay line, so can be called multiple
  // times after a single push() to get the same output sample
  float eval(void) const {
    // y[n] = sum_k c[k] * x[n-k]. A linear-phase FIR has c[k] == c[N-1-k], so the two
    // samples that share a coefficient can be added before the multiply:
    // 65 multiplies instead of 129.

    //TODO -> simplify i,j?

    uint16_t i = idx_ ? (uint16_t)(idx_ - 1) : (uint16_t)(N - 1);  // newest, x[n]
    uint16_t j = idx_;                                              // oldest, x[n-(N-1)]
    float acc = 0.0f;
    for (uint16_t k = 0; k < kHalf; k++) {
      acc += c_[k] * (z_[i] + z_[j]);
      i = i ? (uint16_t)(i - 1) : (uint16_t)(N - 1);
      j = (uint16_t)(j + 1 == N ? 0 : j + 1);
    }
    // After kHalf steps back from the newest sample, i is the centre tap - the one
    // coefficient without a partner.
    return acc + c_[kHalf] * z_[i];
  }

  // The unfiltered input sample that eval() is centred on, i.e. the one kHalf
  // pushes back.
  float center(void) const { return z_[(uint16_t)((idx_ + kHalf) % N)]; }

 private:
  const float *c_;
  float    z_[N] = {0};
  uint16_t idx_ = 0;   // next write slot; the newest sample sits at idx_-1
};

#endif  // FIR_H
